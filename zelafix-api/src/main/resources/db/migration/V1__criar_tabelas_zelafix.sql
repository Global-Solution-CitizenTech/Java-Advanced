-- 1. ESTADO
CREATE TABLE estado (
    id_estado NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nm_estado VARCHAR2(30) NOT NULL,
    CONSTRAINT estado_pk PRIMARY KEY (id_estado)
);

-- 2. CIDADE
CREATE TABLE cidade (
    id_cidade        NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nm_cidade        VARCHAR2(50) NOT NULL,
    estado_id_estado NUMBER(5) NOT NULL,
    CONSTRAINT cidade_pk PRIMARY KEY (id_cidade),
    CONSTRAINT cidade_estado_fk FOREIGN KEY (estado_id_estado) REFERENCES estado(id_estado)
);

-- 3. BAIRRO
CREATE TABLE bairro (
    id_bairro        NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nm_bairro        VARCHAR2(50) NOT NULL,
    cidade_id_cidade NUMBER(5) NOT NULL,
    CONSTRAINT bairro_pk PRIMARY KEY (id_bairro),
    CONSTRAINT bairro_cidade_fk FOREIGN KEY (cidade_id_cidade) REFERENCES cidade(id_cidade)
);

-- 4. ENDERECO
CREATE TABLE endereco (
    id_endereco      NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    cep              VARCHAR2(8) NOT NULL,
    rua              VARCHAR2(100) NOT NULL,
    numero           VARCHAR2(100) NOT NULL,
    referencia       VARCHAR2(50) NOT NULL,
    bairro_id_bairro NUMBER(5) NOT NULL,
    CONSTRAINT endereco_pk PRIMARY KEY (id_endereco),
    CONSTRAINT endereco_bairro_fk FOREIGN KEY (bairro_id_bairro) REFERENCES bairro(id_bairro)
);

-- 5. USUARIO
CREATE TABLE usuario (
    id_usuario           NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nm_usuario           VARCHAR2(100) NOT NULL,
    email                VARCHAR2(100) NOT NULL,
    senha                VARCHAR2(60) NOT NULL,
    cargo                VARCHAR2(10) NOT NULL,
    endereco_id_endereco NUMBER(5) NOT NULL,
    CONSTRAINT usuario_pk PRIMARY KEY (id_usuario),
    CONSTRAINT usuario_email_un UNIQUE (email),
    CONSTRAINT ck_usuario_cargo CHECK (cargo IN ('CIDADAO', 'GESTOR', 'ADMIN')),
    CONSTRAINT usuario_endereco_fk FOREIGN KEY (endereco_id_endereco) REFERENCES endereco(id_endereco)
);

-- 6. TELEFONE
CREATE TABLE telefone (
    id_telefone        NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    num_ddd            VARCHAR2(2) NOT NULL,
    num_tel            VARCHAR2(9) NOT NULL,
    usuario_id_usuario NUMBER(5) NOT NULL,
    CONSTRAINT telefone_pk PRIMARY KEY (id_telefone),
    CONSTRAINT telefone_usuario_fk FOREIGN KEY (usuario_id_usuario) REFERENCES usuario(id_usuario)
);
CREATE UNIQUE INDEX telefone__idx ON telefone(usuario_id_usuario ASC);

-- 7. CATEGORIA
CREATE TABLE categoria (
    id_categoria NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nm_categoria VARCHAR2(50) NOT NULL,
    CONSTRAINT categoria_pk PRIMARY KEY (id_categoria)
);

-- 8. STATUS
CREATE TABLE status (
    id_status NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nm_status VARCHAR2(20) NOT NULL,
    CONSTRAINT status_pk PRIMARY KEY (id_status),
    CONSTRAINT ck_status_nome CHECK (nm_status IN ('PENDENTE', 'EM_ANALISE', 'EM_EXECUCAO', 'CONCLUIDO', 'REJEITADO'))
);

-- 9. PRIORIDADE
CREATE TABLE prioridade (
    id_prioridade NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nm_prioridade VARCHAR2(20) NOT NULL,
    CONSTRAINT prioridade_pk PRIMARY KEY (id_prioridade),
    CONSTRAINT prioridade_nome_un UNIQUE (nm_prioridade)
);

-- 10. ORGAO_GOVERNO
CREATE TABLE orgao_governo (
    id_orgao      NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    orgao_governo VARCHAR2(100) NOT NULL,
    CONSTRAINT orgao_governo_pk PRIMARY KEY (id_orgao),
    CONSTRAINT orgao_governo_nome_un UNIQUE (orgao_governo)
);

-- 11. CHAMADO
CREATE TABLE chamado (
    id_chamado               NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    titulo                   VARCHAR2(100) NOT NULL,
    descricao                VARCHAR2(1000) NOT NULL,
    foto                     BLOB NOT NULL,
    dt_abertura              DATE NOT NULL,
    usuario_id_usuario       NUMBER(5) NOT NULL,
    endereco_id_endereco     NUMBER(5) NOT NULL,
    categoria_id_categoria   NUMBER(5) NOT NULL,
    prioridade_id_prioridade NUMBER(5) NOT NULL,
    orgao_governo_id_orgao   NUMBER(5) NOT NULL,
    CONSTRAINT chamado_pk PRIMARY KEY (id_chamado),
    CONSTRAINT chamado_usuario_fk FOREIGN KEY (usuario_id_usuario) REFERENCES usuario(id_usuario),
    CONSTRAINT chamado_endereco_fk FOREIGN KEY (endereco_id_endereco) REFERENCES endereco(id_endereco),
    CONSTRAINT chamado_categoria_fk FOREIGN KEY (categoria_id_categoria) REFERENCES categoria(id_categoria),
    CONSTRAINT chamado_prioridade_fk FOREIGN KEY (prioridade_id_prioridade) REFERENCES prioridade(id_prioridade),
    CONSTRAINT chamado_orgao_fk FOREIGN KEY (orgao_governo_id_orgao) REFERENCES orgao_governo(id_orgao)
);

-- 12. HIST_CHAMADO
CREATE TABLE hist_chamado (
    id_hist            NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    dt_mudanca         DATE NOT NULL,
    observacoes        VARCHAR2(255) NOT NULL,
    chamado_id_chamado NUMBER(5) NOT NULL,
    usuario_id_usuario NUMBER(5) NOT NULL,
    status_id_status   NUMBER(5) NOT NULL,
    CONSTRAINT hist_chamado_pk PRIMARY KEY (id_hist),
    CONSTRAINT hist_chamado_chamado_fk FOREIGN KEY (chamado_id_chamado) REFERENCES chamado(id_chamado),
    CONSTRAINT hist_chamado_usuario_fk FOREIGN KEY (usuario_id_usuario) REFERENCES usuario(id_usuario),
    CONSTRAINT hist_chamado_status_fk FOREIGN KEY (status_id_status) REFERENCES status(id_status)
);

-- 13. VOTO_CHAMADO
CREATE TABLE voto_chamado (
    id_voto            NUMBER(5) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    dt_voto            DATE NOT NULL,
    chamado_id_chamado NUMBER(5) NOT NULL,
    usuario_id_usuario NUMBER(5) NOT NULL,
    CONSTRAINT voto_chamado_pk PRIMARY KEY (id_voto),
    CONSTRAINT voto_chamado_un UNIQUE (chamado_id_chamado, usuario_id_usuario),
    CONSTRAINT voto_chamado_chamado_fk FOREIGN KEY (chamado_id_chamado) REFERENCES chamado(id_chamado),
    CONSTRAINT voto_chamado_usuario_fk FOREIGN KEY (usuario_id_usuario) REFERENCES usuario(id_usuario)
);

-- Índices em Foreign Keys
CREATE INDEX idx_cidade_estado ON cidade(estado_id_estado);
CREATE INDEX idx_bairro_cidade ON bairro(cidade_id_cidade);
CREATE INDEX idx_endereco_bairro ON endereco(bairro_id_bairro);
CREATE INDEX idx_usuario_endereco ON usuario(endereco_id_endereco);
CREATE INDEX idx_chamado_usuario ON chamado(usuario_id_usuario);
CREATE INDEX idx_chamado_endereco ON chamado(endereco_id_endereco);
CREATE INDEX idx_chamado_categoria ON chamado(categoria_id_categoria);
CREATE INDEX idx_chamado_prioridade ON chamado(prioridade_id_prioridade);
CREATE INDEX idx_chamado_orgao ON chamado(orgao_governo_id_orgao);
CREATE INDEX idx_hist_chamado_chamado ON hist_chamado(chamado_id_chamado);
CREATE INDEX idx_hist_chamado_usuario ON hist_chamado(usuario_id_usuario);
CREATE INDEX idx_hist_chamado_status ON hist_chamado(status_id_status);
CREATE INDEX idx_voto_chamado ON voto_chamado(chamado_id_chamado);
CREATE INDEX idx_voto_usuario ON voto_chamado(usuario_id_usuario);
